  // Ambient Xianxia Guzheng / Taoist flute pentatonic tune
  public toggleMusic(): boolean {
    if (this.isMusicPlaying) {
      this.stopMusic();
      return false;
    } else {
      this.startMusic();
      return true;
    }
  }

  private startMusic() {
    this.initCtx();
    this.isMusicPlaying = true;
    // Pentatonic scale (D, F#, G, A, C#)
    const scale = [293.66, 369.99, 392.00, 440.00, 554.37, 587.33, 739.99, 880.00];

    const playNote = () => {
      if (!this.isMusicPlaying || this.isMuted || !this.ctx) return;
      const freq = scale[Math.floor(Math.random() * scale.length)];
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();

      osc.type = 'triangle';
      osc.frequency.setValueAtTime(freq, this.ctx.currentTime);

      gain.gain.setValueAtTime(0.001, this.ctx.currentTime);
      gain.gain.linearRampToValueAtTime(0.06, this.ctx.currentTime + 0.05);
      gain.gain.exponentialRampToValueAtTime(0.001, this.ctx.currentTime + 1.2);

      osc.connect(gain);
      gain.connect(this.ctx.destination);

      osc.start();
      osc.stop(this.ctx.currentTime + 1.2);
    };

    // Play periodic soothing oriental notes
    this.musicInterval = window.setInterval(() => {
      playNote();
      if (Math.random() > 0.4) {
        setTimeout(playNote, 250);
      }
    }, 1100);
  }

  private stopMusic() {
    this.isMusicPlaying = false;
    if (this.musicInterval) {
      clearInterval(this.musicInterval);
      this.musicInterval = null;
    }
  }

